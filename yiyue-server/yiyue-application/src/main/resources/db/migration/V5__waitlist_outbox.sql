CREATE TABLE waitlist_entry (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL REFERENCES tenant(id), user_id BIGINT NOT NULL REFERENCES app_user(id),
 patient_id BIGINT NOT NULL REFERENCES patient_profile(id), slot_id BIGINT NOT NULL REFERENCES appointment_slot(id),
 status VARCHAR(20) NOT NULL, expires_at TIMESTAMP, appointment_id BIGINT REFERENCES appointment(id), created_at TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX uq_waitlist_active ON waitlist_entry(tenant_id,patient_id,slot_id) WHERE status IN ('WAITING','OFFERED');
CREATE INDEX idx_waitlist_slot ON waitlist_entry(tenant_id,slot_id,status,id);
CREATE TABLE notification_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id BIGINT NOT NULL REFERENCES tenant(id),
 user_id BIGINT NOT NULL REFERENCES app_user(id), event_key VARCHAR(100) NOT NULL UNIQUE,
 message VARCHAR(300) NOT NULL, delivered BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP NOT NULL
);
CREATE TABLE inbox_message (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id BIGINT NOT NULL REFERENCES tenant(id),
 user_id BIGINT NOT NULL REFERENCES app_user(id), event_id BIGINT NOT NULL UNIQUE REFERENCES notification_event(id),
 message VARCHAR(300) NOT NULL, read_at TIMESTAMP, created_at TIMESTAMP NOT NULL
);
